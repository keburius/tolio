import Foundation

/// A result a feature contributes to palette search (clipboard items, snippets…).
public struct SearchResult: Identifiable, Sendable {
    public enum Icon: Sendable, Hashable {
        case symbol(String)
        /// Use the Finder icon of this file.
        case file(URL)
        /// Show this image file (a small thumbnail).
        case image(URL)
    }

    public let id: String
    public let title: String
    public let subtitle: String?
    public let icon: Icon
    /// Runs on ↩, after the palette has closed.
    public let primaryAction: @MainActor @Sendable () -> Void
    /// Runs on ⌘↩, if present.
    public let alternateAction: (@MainActor @Sendable () -> Void)?

    public init(
        id: String, title: String, subtitle: String? = nil, icon: Icon,
        primaryAction: @escaping @MainActor @Sendable () -> Void,
        alternateAction: (@MainActor @Sendable () -> Void)? = nil
    ) {
        self.id = id
        self.title = title
        self.subtitle = subtitle
        self.icon = icon
        self.primaryAction = primaryAction
        self.alternateAction = alternateAction
    }
}

/// Supplies dynamic results to the palette. Typing "<keyword> " in the
/// palette shows only this provider's results; otherwise its best few
/// matches are mixed into normal search.
@MainActor
public protocol SearchProvider: AnyObject {
    /// Prefix that scopes the palette to this provider, e.g. "clip".
    var keyword: String { get }
    /// Section label, e.g. "Clipboard".
    var title: String { get }
    /// Results for `query`; an empty query means "most recent".
    func results(for query: String, limit: Int) -> [SearchResult]
}

/// Well-known pasteboard types (see nspasteboard.org).
public enum PasteboardTypes {
    /// Password managers mark secrets with this; never store such items.
    public static let concealed = "org.nspasteboard.ConcealedType"
    /// Data that is only on the pasteboard briefly.
    public static let transient = "org.nspasteboard.TransientType"
    /// Data an app put there automatically, not by user action.
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Marks Omni's own temporary writes and restores so history ignores them.
    public static let omniInternal = "com.george.omni.internal"
}
