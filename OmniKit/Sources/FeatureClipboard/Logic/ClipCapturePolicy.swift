import OmniCore

/// Why a pasteboard change was not recorded. Logged by reason only, never with content.
public enum ClipSkipReason: Equatable, Sendable {
    case concealed
    case transient
    case autoGenerated
    case ownWrite
    case excludedApp(String)
    case unsupportedContent
    case tooLarge
}

/// Decides whether a pasteboard change may be stored. Pure function of the
/// pasteboard's type list and the app that was frontmost.
public enum ClipCapturePolicy {
    /// Older private markers some password managers and tools still use.
    static let legacySecretTypes: Set<String> = [
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping",
        "net.antelle.keeweb",
    ]

    /// Password managers whose copies are never stored, even if they forget
    /// to mark the item concealed. Users can't remove these.
    public static let builtInExcludedApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "org.keepassxc.keepassxc", "com.bitwarden.desktop", "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal", "com.dashlane.Dashlane", "com.apple.Passwords",
        "com.apple.keychainaccess", "in.sinew.Enpass-Desktop", "com.nordpass.macos.NordPass",
        "com.proton.pass.electron",
    ]

    /// `nil` means the change may be stored.
    public static func skipReason(
        types: Set<String>, sourceBundleID: String?, userExcludedApps: Set<String>
    ) -> ClipSkipReason? {
        if types.contains(PasteboardTypes.concealed) || !types.isDisjoint(with: legacySecretTypes) { return .concealed }
        if types.contains(PasteboardTypes.omniInternal) { return .ownWrite }
        if types.contains(PasteboardTypes.transient) { return .transient }
        if types.contains(PasteboardTypes.autoGenerated) { return .autoGenerated }
        if let app = sourceBundleID, builtInExcludedApps.contains(app) || userExcludedApps.contains(app) {
            return .excludedApp(app)
        }
        return nil
    }
}
