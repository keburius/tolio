@testable import FeatureClipboard
import OmniCore
import Testing

struct ClipCapturePolicyTests {
    private func reason(_ types: Set<String>, app: String? = "com.apple.TextEdit", excluded: Set<String> = []) -> ClipSkipReason? {
        ClipCapturePolicy.skipReason(types: types, sourceBundleID: app, userExcludedApps: excluded)
    }

    @Test func plainTextIsStored() {
        #expect(reason(["public.utf8-plain-text"]) == nil)
    }

    @Test func concealedIsNeverStored() {
        #expect(reason(["public.utf8-plain-text", PasteboardTypes.concealed]) == .concealed)
        #expect(reason(["public.utf8-plain-text", "com.agilebits.onepassword"]) == .concealed)
    }

    @Test func concealedWinsOverEverythingElse() {
        // Even an excluded or own write that is concealed reports concealed.
        let types: Set<String> = [PasteboardTypes.concealed, PasteboardTypes.omniInternal, PasteboardTypes.transient]
        #expect(reason(types) == .concealed)
    }

    @Test func transientAutoGeneratedAndOwnWritesAreSkipped() {
        #expect(reason([PasteboardTypes.transient]) == .transient)
        #expect(reason([PasteboardTypes.autoGenerated]) == .autoGenerated)
        #expect(reason([PasteboardTypes.omniInternal, "public.utf8-plain-text"]) == .ownWrite)
    }

    @Test func passwordManagersAreAlwaysExcluded() {
        #expect(reason(["public.utf8-plain-text"], app: "com.1password.1password") == .excludedApp("com.1password.1password"))
        #expect(reason(["public.utf8-plain-text"], app: "com.apple.Passwords") == .excludedApp("com.apple.Passwords"))
    }

    @Test func userExcludeList() {
        #expect(reason(["public.utf8-plain-text"], app: "com.tinyspeck.slackmacgap", excluded: ["com.tinyspeck.slackmacgap"])
            == .excludedApp("com.tinyspeck.slackmacgap"))
        #expect(reason(["public.utf8-plain-text"], app: nil, excluded: ["x"]) == nil)
    }
}
